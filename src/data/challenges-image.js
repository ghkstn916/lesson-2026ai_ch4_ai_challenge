/**
 * 5요소(주제·스타일·구도·라이팅·디테일)를 이미지 생성용 완성 프롬프트로 합친다.
 * 이미지 모델이 메타 라벨을 글자로 그리지 않도록, 라벨 없이 자연스러운 쉼표 나열로 합친다.
 * (학생은 합쳐진 결과를 화면에서 직접 더 다듬을 수 있다.)
 */
export function composeImagePrompt(parts) {
  return IMAGE_ELEMENTS.map((e) => (parts[e.key] || '').trim())
    .filter(Boolean)
    .join(', ')
}

