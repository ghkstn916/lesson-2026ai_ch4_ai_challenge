/**
 * 4요소 → 완성 프롬프트 합성.
 * 학생 화면과 AI에게 보내는 본문이 동일하게 라벨링되어 있어
 * "어떤 요소가 어디로 들어가는지" 학습 효과를 살림.
 */
export function composeWarmupPrompt(parts, challenge) {
  return [
    `[역할] ${parts.role || ''}`,
    `[맥락] ${parts.context || ''}`,
    `[출력] ${parts.output || ''}`,
    `[조건] ${parts.condition || ''}`,
    '',
    `미션: ${challenge.title} — ${challenge.description}`,
  ].join('\n')
}

